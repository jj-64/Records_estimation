season_max <- data %>%
  mutate(
    date = mdy(date),
    year_raw = year(date),
    month_num = month(date),
    # Assign standard meteorological seasons
    season = case_when(
      month_num %in% c(12, 1, 2)  ~ "Winter",
      month_num %in% c(3, 4, 5)   ~ "Spring",
      month_num %in% c(6, 7, 8)   ~ "Summer",
      month_num %in% c(9, 10, 11) ~ "Autumn"
    ),
    # Shift December to belong to the next year's winter season
    # (e.g., Dec 1950 is part of the 1951 Winter season)
    year = if_else(month_num == 12, year_raw + 1, year_raw)
  ) %>%
  # Group by the seasonal year and the season name
  group_by(year, season) %>%
  summarise(max_data = max(price, na.rm = TRUE), .groups = "drop") %>%
  # Clean up -Inf values generated by max() on all-NA blocks
  mutate(max_data = ifelse(is.infinite(max_data), NA, max_data)) %>%
  # Ensure chronological order for the legend
  mutate(season = factor(season, levels = c("Winter", "Spring", "Summer", "Autumn")))

ggplot(season_max, aes(x = year, y = max_data, color = season, group = season)) +
  geom_line(linewidth = 1) +
