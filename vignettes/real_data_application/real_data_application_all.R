# Define model metadata configurations
models_config <- list(
  list(id = "H0", loglik = logLikH0, pars = param_H0_start[c("gamma", "location", "scale")], names = c("gamma", "location", "scale")),
  list(id = "H1", loglik = logLikH1, pars = param_H1_start[c("location", "scale")], names = c("location", "scale")),
  list(id = "H2", loglik = logLikH2, pars = param_H2_start[c("mean","sd")], names = c("mean","sd")),
  list(id = "H3", loglik = logLikH3, pars = param_H3_start[c("theta", "shape", "scale")], names = c("theta", "shape", "scale"))
)

# Compute metrics dynamically using a map loop
all_models_df <- map_dfr(models_config, function(m) {

  # Compute Hessian and extract standard errors
  hess <- compute_hessian(m$loglik, data = x, par_vec = m$pars)
  se   <- sqrt(diag(hess$vcov))

  # Return structured dataframe per model
  data.frame(
    model         = m$id,
    parameter_idx = seq_along(m$pars),
    param_name    = m$names,
    estimate      = m$pars,
    std_error     = se,
    lower_ci      = m$pars - 1.96 * se,
    upper_ci      = m$pars + 1.96 * se,
    row.names     = NULL

  )
})

# View the final unified dataframe
